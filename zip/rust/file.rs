impl<'a> Read for CallbackZipFile<'a> {
    fn read(&mut self, buf: &mut [u8]) -> std::io::Result<usize> {
        match self.file.as_mut() {
            Some(file) => file.read(buf),
            None => Err(Error::new(ErrorKind::InvalidInput, "ZipFile is not available")),
        }
    }
}

fn get_file_name_impl<'a, R: Read>(file: &Option<Box<WrappedZipFile<'a, R>>>) -> VecU8 {
    match file.as_ref() {
        Some(file) => match file.name() {
            Ok(name) => VecU8::from(name.as_ref()),
            Err(_) => VecU8::copy_from_slice(file.name_raw()),
        },
        None => VecU8::default(),
    }
}

fn is_file_impl<'a, R: Read>(file: &Option<Box<WrappedZipFile<'a, R>>>) -> bool {
    match file.as_ref() {
        Some(file) => file.is_file(),
        None => false,
    }
}

fn is_dir_impl<'a, R: Read>(file: &Option<Box<WrappedZipFile<'a, R>>>) -> bool {
    match file.as_ref() {
        Some(file) => file.is_dir(),
        None => false,
    }
}

fn get_comment_impl<'a, R: Read>(file: &Option<Box<WrappedZipFile<'a, R>>>) -> VecU8 {
    file.as_ref().map(|f| VecU8::from(f.comment())).unwrap_or_default()
}

fn get_uncompressed_size_impl<'a, R: Read>(file: &Option<Box<WrappedZipFile<'a, R>>>) -> u64 {
    file.as_ref().map(|f| f.size()).unwrap_or(0)
}

fn get_compressed_size_impl<'a, R: Read>(file: &Option<Box<WrappedZipFile<'a, R>>>) -> u64 {
    file.as_ref().map(|f| f.compressed_size()).unwrap_or(0)
}

fn get_crc32_impl<'a, R: Read>(file: &Option<Box<WrappedZipFile<'a, R>>>) -> u32 {
    file.as_ref().map(|f| f.crc32()).unwrap_or(0)
}

fn get_last_modified_date_impl<'a, R: Read>(file: &Option<Box<WrappedZipFile<'a, R>>>) -> u16 {
    file.as_ref().and_then(|f| f.last_modified()).map(|dt| dt.datepart()).unwrap_or(0)
}

fn get_last_modified_time_impl<'a, R: Read>(file: &Option<Box<WrappedZipFile<'a, R>>>) -> u16 {
    file.as_ref().and_then(|f| f.last_modified()).map(|dt| dt.timepart()).unwrap_or(0)
}

fn get_unix_mode_impl<'a, R: Read>(file: &Option<Box<WrappedZipFile<'a, R>>>) -> u32 {
    file.as_ref().and_then(|f| f.unix_mode()).unwrap_or(0)
}

fn get_extra_data_impl<'a, R: Read>(file: &Option<Box<WrappedZipFile<'a, R>>>) -> VecU8 {
    file.as_ref().and_then(|f| f.extra_data()).map(VecU8::from).unwrap_or_default()
}

fn get_header_start_impl<'a, R: Read>(file: &Option<Box<WrappedZipFile<'a, R>>>) -> u64 {
    match file.as_ref() {
        Some(file) => file.header_start(),
        None => 0,
    }
}

fn get_data_start_impl<'a, R: Read>(file: &Option<Box<WrappedZipFile<'a, R>>>) -> u64 {
    match file.as_ref() {
        // `data_start` is `None` until the local file header has been parsed,
        // and a real entry can never start at offset 0 because the header
        // itself occupies at least 30 bytes, so 0 is unambiguously "unknown".
        Some(file) => file.data_start().unwrap_or(0),
        None => 0,
    }
}

fn get_compression_method_impl<'a, R: Read>(
    file: &Option<Box<WrappedZipFile<'a, R>>>,
) -> CompressionMethod {
    match file.as_ref() {
        Some(file) => CompressionMethod::from_zip_crate(file.compression()),
        None => CompressionMethod::Unsupported,
    }
}

fn get_file_data_impl<'a, R: Read>(
    file: &mut Option<Box<WrappedZipFile<'a, R>>>,
) -> Result<VecU8, ZipError> {
    match file.as_mut() {
        Some(file) => {
            let mut buffer = Vec::new();
            match file.read_to_end(&mut buffer) {
                Ok(_) => Ok(buffer.into()),
                Err(e) => Err(ZipError::internal(e.to_string())),
            }
        }
        None => Err(ZipError::internal("ZipFile is not available")),
    }
}

fn get_file_data_with_max_size_impl<'a, R: Read>(
    file: &mut Option<Box<WrappedZipFile<'a, R>>>,
    max_size: usize,
) -> Result<VecU8, ZipError> {
    match file.as_mut() {
        Some(file) => {
            let mut buffer = Vec::new();
            let limit = (max_size as u64).saturating_add(1);
            match (&mut **file).take(limit).read_to_end(&mut buffer) {
                Ok(_) => {
                    if buffer.len() > max_size {
                        Err(ZipError::out_of_range(format!(
                            "Decompressed entry size exceeds maximum allowed size of {} bytes",
                            max_size
                        )))
                    } else {
                        Ok(buffer.into())
                    }
                }
                Err(e) => Err(ZipError::internal(e.to_string())),
            }
        }
        None => Err(ZipError::internal("ZipFile is not available")),
    }
}

fn read_bytes_impl<'a, R: Read>(
    file: &mut Option<Box<WrappedZipFile<'a, R>>>,
    max_bytes: usize,
) -> Result<VecU8, ZipError> {
    match file.as_mut() {
        Some(file) => {
            // Grow the buffer only as data arrives instead of eagerly
            // allocating `max_bytes` (which is caller-chosen and may be huge).
            let mut buffer = Vec::new();
            match (&mut **file).take(max_bytes as u64).read_to_end(&mut buffer) {
                Ok(_) => Ok(buffer.into()),
                Err(e) => Err(ZipError::internal(e.to_string())),
            }
        }
        None => Err(ZipError::internal("ZipFile is not available")),
    }
}

fn read_into_impl<'a, R: Read>(
    file: &mut Option<Box<WrappedZipFile<'a, R>>>,
    buf: &mut [u8],
) -> Result<u64, ZipError> {
    let Some(file) = file.as_mut() else {
        return Err(ZipError::internal("ZipFile is not available"));
    };
    // A decompressor returns what the current block happens to yield, which is
    // routinely less than was asked for, so fill the buffer here rather than
    // making the caller loop -- across a language boundary, in C++'s case.
    let mut filled = 0usize;
    while filled < buf.len() {
        match file.read(&mut buf[filled..]) {
            Ok(0) => break,
            Ok(bytes_read) => filled += bytes_read,
            // Read contracts allow this and it means nothing was consumed.
            Err(e) if e.kind() == ErrorKind::Interrupted => {}
            Err(e) => return Err(ZipError::internal(e.to_string())),
        }
    }
    Ok(filled as u64)
}

fn skip_impl<'a, R: Read>(
    file: &mut Option<Box<WrappedZipFile<'a, R>>>,
    max_bytes: u64,
) -> Result<u64, ZipError> {
    let Some(file) = file.as_mut() else {
        return Err(ZipError::internal("ZipFile is not available"));
    };
    // `io::copy` drives this with a reused stack buffer, so a long skip costs
    // no allocation however far it goes.
    std::io::copy(&mut (&mut **file).take(max_bytes), &mut std::io::sink())
        .map_err(|e| ZipError::internal(e.to_string()))
}
