/// A zip entry together with the bookkeeping needed to reject, when the end of
/// the entry is reached, a payload that decoded to fewer bytes than the archive
/// declared.
///
/// zip-rs already fails as soon as *more* bytes than the declared
/// `uncompressed_size` come out, and verifies the CRC-32 on the read that
/// observes end of entry, but it accepts a stream that ends early with a CRC-32
/// matching the shorter payload. libzip reports such an archive as inconsistent,
/// and without this check every caller would have to compare lengths itself.
struct Entry<'a, R: Read> {
    file: WrappedZipFile<'a, R>,
    /// Decoded bytes handed out so far, across every read and skip.
    bytes_read: u64,
    /// The `uncompressed_size` the entry must decode to, when it is known. It
    /// is unknown for entries opened raw (they yield the compressed bytes) and
    /// for streamed entries whose sizes only follow the data in a data
    /// descriptor (the same cases in which zip-rs cannot bound the output).
    expected_size: Option<u64>,
}

impl<'a, R: Read> Entry<'a, R> {
    fn new(file: WrappedZipFile<'a, R>, raw: bool) -> Self {
        // Only a `*ZipStreamReader` hands out entries before their local file
        // header offset is known; an archive parses it when opening the entry.
        let streamed = file.data_start().is_none();
        let size_unknown = raw || (streamed && file.flags().is_using_data_descriptor());
        let expected_size = (!size_unknown).then_some(file.size());
        Self { file, bytes_read: 0, expected_size }
    }

    fn count(&mut self, n: usize) {
        self.bytes_read = self.bytes_read.saturating_add(n as u64);
    }

    /// Called once the end of the entry has been observed.
    fn check_declared_size(&self) -> std::io::Result<()> {
        match self.expected_size {
            Some(expected) if self.bytes_read != expected => Err(Error::new(
                ErrorKind::InvalidData,
                format!(
                    "Entry decoded to {} bytes but its header declares {}",
                    self.bytes_read, expected
                ),
            )),
            _ => Ok(()),
        }
    }
}

impl<'a, R: Read> Read for Entry<'a, R> {
    fn read(&mut self, buf: &mut [u8]) -> std::io::Result<usize> {
        let n = self.file.read(buf)?;
        if n == 0 {
            // zip-rs reports end of entry (and checks the CRC-32) on the first
            // read that returns 0 for a non-empty buffer.
            if !buf.is_empty() {
                self.check_declared_size()?;
            }
        } else {
            self.count(n);
        }
        Ok(n)
    }

    fn read_to_end(&mut self, buf: &mut Vec<u8>) -> std::io::Result<usize> {
        let n = self.file.read_to_end(buf)?;
        self.count(n);
        self.check_declared_size()?;
        Ok(n)
    }
}

#[derive(Default)]
pub struct BufferedZipFile<'a> {
    /// file is never None except for the default value, which is only
    /// used by Crubit to generate movable types.
    /// In C++, whenever a method of *ZipFile is called, the file must be
    /// checked to be not None first.
    file: Option<Box<Entry<'a, Cursor<Vec<u8>>>>>,
}

impl<'a> Debug for BufferedZipFile<'a> {
    fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("BufferedZipFile")
            .field("file", &if self.file.is_some() { "Some(BufferedZipFile)" } else { "None" })
            .finish()
    }
}

impl<'a> BufferedZipFile<'a> {
    /// Creates a new BufferedZipFile.
    /// This function won't be generated by Crubit and is only called from rust.
    /// (b/259749095)
    pub fn new(file: WrappedZipFile<'a, Cursor<Vec<u8>>>) -> Self {
        Self { file: Some(Box::new(Entry::new(file, /* raw= */ false))) }
    }

    /// Creates a new BufferedZipFile over an entry opened raw (`get_file_by_index_raw`),
    /// whose reads yield the stored bytes without decompression, CRC-32 or
    /// declared-size verification.
    /// This function won't be generated by Crubit and is only called from rust.
    pub fn new_raw(file: WrappedZipFile<'a, Cursor<Vec<u8>>>) -> Self {
        Self { file: Some(Box::new(Entry::new(file, /* raw= */ true))) }
    }

    /// Returns whether the zip file is none (due to being default-constructed
    /// or moved-from).
    #[must_use]
    pub fn is_none(&self) -> bool {
        self.file.is_none()
    }

    /// Returns the name of the file.
    /// The result is only valid if `is_none()` returns false.
    pub fn get_file_name(&self) -> VecU8 {
        get_file_name_impl(&self.file)
    }

    /// Returns whether the entry is a file.
    /// The result is only valid if `is_none()` returns false.
    pub fn is_file(&self) -> bool {
        is_file_impl(&self.file)
    }

    /// Returns whether the entry is a directory.
    /// The result is only valid if `is_none()` returns false.
    pub fn is_dir(&self) -> bool {
        is_dir_impl(&self.file)
    }

    /// Returns the compression method of the file.
    /// The result is only valid if `is_none()` returns false.
    pub fn get_compression_method(&self) -> CompressionMethod {
        get_compression_method_impl(&self.file)
    }

    /// Returns the comment of the file.
    /// The result is only valid if `is_none()` returns false.
    pub fn get_comment(&self) -> VecU8 {
        get_comment_impl(&self.file)
    }

    /// Returns the uncompressed size of the file.
    /// The result is only valid if `is_none()` returns false.
    pub fn get_uncompressed_size(&self) -> u64 {
        get_uncompressed_size_impl(&self.file)
    }

    /// Returns the compressed size of the file.
    /// The result is only valid if `is_none()` returns false.
    pub fn get_compressed_size(&self) -> u64 {
        get_compressed_size_impl(&self.file)
    }

    /// Returns the CRC32 of the file.
    /// The result is only valid if `is_none()` returns false.
    pub fn get_crc32(&self) -> u32 {
        get_crc32_impl(&self.file)
    }

    /// Returns the last modified date of the file in DOS format.
    /// The result is only valid if `is_none()` returns false.
    pub fn get_last_modified_date(&self) -> u16 {
        get_last_modified_date_impl(&self.file)
    }

    /// Returns the last modified time of the file in DOS format.
    /// The result is only valid if `is_none()` returns false.
    pub fn get_last_modified_time(&self) -> u16 {
        get_last_modified_time_impl(&self.file)
    }

    /// Returns the Unix mode of the file.
    /// The result is only valid if `is_none()` returns false.
    pub fn get_unix_mode(&self) -> u32 {
        get_unix_mode_impl(&self.file)
    }

    /// Returns the extra data of the file.
    /// The result is only valid if `is_none()` returns false.
    pub fn get_extra_data(&self) -> VecU8 {
        get_extra_data_impl(&self.file)
    }

    /// Returns the offset of this entry's local file header within the archive.
    ///
    /// Only meaningful for entries opened from a `*ZipArchive`: entries
    /// obtained from a `*ZipStreamReader` do not know their offset and always
    /// report 0, which is indistinguishable from the genuine offset of an
    /// archive's first entry.
    ///
    /// The result is only valid if `is_none()` returns false.
    #[must_use]
    pub fn get_header_start(&self) -> u64 {
        get_header_start_impl(&self.file)
    }

    /// Returns the offset of this entry's data within the archive, or 0 if it
    /// is unknown. Together with `get_compressed_size()` this delimits the
    /// entry's raw bytes, so a caller that only needs a `Stored` entry can read
    /// that byte range directly instead of going through this archive.
    ///
    /// The offset is only known once the local file header has been parsed,
    /// which archive-based readers do when the entry is opened. It is never
    /// known for entries obtained from a `*ZipStreamReader`, which report 0.
    ///
    /// The result is only valid if `is_none()` returns false.
    #[must_use]
    pub fn get_data_start(&self) -> u64 {
        get_data_start_impl(&self.file)
    }

    /// Returns the data of the file, verified against the entry's CRC-32 and
    /// declared `uncompressed_size`.
    /// Returns an error if `is_none()` returns true.
    pub fn get_file_data(&mut self) -> Result<VecU8, ZipError> {
        get_file_data_impl(&mut self.file)
    }

    /// Returns the data of the file if its decompressed size does not exceed
    /// `max_size` bytes.
    /// Returns an error if `is_none()` returns true.
    pub fn get_file_data_with_max_size(&mut self, max_size: usize) -> Result<VecU8, ZipError> {
        get_file_data_with_max_size_impl(&mut self.file, max_size)
    }

    /// Reads up to `max_bytes` decompressed bytes from the file.
    /// With `max_bytes > 0`, returns an empty `VecU8` only at EOF
    /// (`read_bytes(0)` returns an empty `VecU8` without advancing the file).
    /// Returns an error if `is_none()` returns true.
    pub fn read_bytes(&mut self, max_bytes: usize) -> Result<VecU8, ZipError> {
        read_bytes_impl(&mut self.file, max_bytes)
    }

    /// Reads into `buf` (decompressing unless the entry was opened raw) and
    /// returns how many bytes were written, which is less than `buf.len()`
    /// only at end of entry.
    ///
    /// Unlike `read_bytes`, nothing is allocated and the bytes are not copied
    /// again on the way out, so this is what a caller reading an entry of any
    /// size should use.
    ///
    /// The CRC-32 and the declared `uncompressed_size` are verified only by
    /// the read that reaches the end of the entry, so reading exactly the
    /// uncompressed size never checks them; read until a short count (or 0) to
    /// have the entry validated. Entries opened raw (`get_file_by_index_raw`)
    /// are never checked.
    ///
    /// Returns an error if `is_none()` returns true,
    /// `ZipErrorCode::Internal` on decompression or CRC errors, or propagates
    /// underlying I/O error codes. On error, the contents of `buf` and the
    /// position within the entry are unspecified.
    pub fn read_into(&mut self, buf: &mut [u8]) -> Result<u64, ZipError> {
        read_into_impl(&mut self.file, buf)
    }

    /// Discards up to `max_bytes` and returns how many were discarded, which
    /// is less than `max_bytes` only at end of entry.
    ///
    /// A zip entry is a forward-only stream, so this is how a caller seeks
    /// within one. Nothing is allocated, whatever the distance.
    ///
    /// As with `read_into`, the CRC-32 and the declared `uncompressed_size`
    /// are checked only by the read or skip that reaches the end of the entry,
    /// so skipping exactly the uncompressed size never checks them, and entries
    /// opened raw (`get_file_by_index_raw`) are never checked.
    ///
    /// Returns an error if `is_none()` returns true,
    /// `ZipErrorCode::Internal` on decompression or CRC errors, or propagates
    /// underlying I/O error codes. On error, the position within the entry is
    /// unspecified.
    pub fn skip(&mut self, max_bytes: u64) -> Result<u64, ZipError> {
        skip_impl(&mut self.file, max_bytes)
    }
}

