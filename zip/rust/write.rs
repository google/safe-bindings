/// A zip writer that streams to a file on the filesystem without seeking.
#[derive(Default)]
pub struct FsZipStreamWriter {
    writer: Option<Box<InnerFsStreamWriter>>,
}

impl Debug for FsZipStreamWriter {
    fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("FsZipStreamWriter")
            .field(
                "writer",
                &if self.writer.is_some() {
                    "Some(WrappedZipWriter<StreamWriter<BufWriter<File>>>)"
                } else {
                    "None"
                },
            )
            .finish()
    }
}

impl FsZipStreamWriter {
    /// Creates a none `FsZipStreamWriter` (Crubit requires `Default`); every
    /// method on it returns FailedPrecondition until it is replaced by
    /// `new_from_path()`.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Creates a new streaming `FsZipStreamWriter` writing to `path`. The file
    /// is created or truncated; there is no append mode.
    pub fn new_from_path(path: &[u8]) -> Result<Self, ZipError> {
        let mut writer = Self::default();
        writer.open(path)?;
        Ok(writer)
    }

    fn open(&mut self, path: &[u8]) -> Result<(), ZipError> {
        if self.writer.is_some() {
            return Err(ZipError::failed_precondition("Zip writer is already open"));
        }
        let path_str = ZipError::validate_non_empty_utf8_path(path, "Failed to open zip archive")?;
        let file =
            OpenOptions::new().write(true).create(true).truncate(true).open(path_str).map_err(
                |e| ZipError::from_io_error(e).with_context("Failed to open zip archive"),
            )?;
        self.writer = Some(Box::new(WrappedZipWriter::new_stream(BufWriter::new(file))));
        Ok(())
    }

    /// Returns whether the zip writer is none (due to being
    /// default-constructed or moved-from).
    #[must_use]
    pub fn is_none(&self) -> bool {
        self.writer.is_none()
    }

    /// Returns whether seeking is possible (always false for stream writers).
    #[must_use]
    pub fn is_seek_possible(&self) -> bool {
        false
    }

    /// Finishes writing the zip archive to file, flushing the buffered writer
    /// so that every byte of the archive has been handed to the OS when this
    /// returns.
    pub fn finish(&mut self) -> Result<(), ZipError> {
        let buf_writer = finish_impl(&mut self.writer)?.into_inner();
        // `into_inner` flushes the buffer; on failure it hands back the
        // `BufWriter`, which is dropped here together with the file.
        buf_writer.into_inner().map(|_| ()).map_err(|e| {
            ZipError::from_io_error(e.into_error()).with_context("Failed to flush zip archive")
        })
    }

    /// Creates a new file in the zip archive and starts writing to it.
    pub fn start_file(
        &mut self,
        name: &[u8],
        options: ZipWriterFileOptions,
    ) -> Result<(), ZipError> {
        start_file_impl(&mut self.writer, name, options)
    }

    /// Adds a directory to the zip archive.
    pub fn add_directory(
        &mut self,
        name: &[u8],
        options: ZipWriterFileOptions,
    ) -> Result<(), ZipError> {
        add_directory_impl(&mut self.writer, name, options)
    }

    /// Writes data to the current file in the zip archive.
    pub fn write_data(&mut self, data: VecU8) -> Result<(), ZipError> {
        write_data_impl(&mut self.writer, data)
    }

    /// Writes file content from a `BufferedZipFile` to the current file in the zip archive.
    pub fn write_buffered_zip_file_content(
        &mut self,
        file: &mut BufferedZipFile,
    ) -> Result<(), ZipError> {
        do_copy_impl(&mut self.writer, file)
    }

    /// Writes file content from a `FsZipFile` to the current file in the zip archive.
    pub fn write_fs_zip_file_content(&mut self, file: &mut FsZipFile) -> Result<(), ZipError> {
        do_copy_impl(&mut self.writer, file)
    }

    /// Writes file content from a path to the current file in the zip archive.
    pub fn write_file_content(&mut self, path: &[u8]) -> Result<(), ZipError> {
        write_file_content_impl(&mut self.writer, path)
    }

    /// Archive comments are not supported by streaming writers; see
    /// `set_stream_comment_impl`. Always returns a FailedPrecondition error.
    pub fn set_comment(&mut self, _comment: &[u8]) -> Result<(), ZipError> {
        set_stream_comment_impl(&self.writer)
    }

    /// Flushes the underlying sink; does not finalize the archive.
    pub fn flush(&mut self) -> Result<(), ZipError> {
        flush_impl(&mut self.writer)
    }
}

/// Creates a new in-memory streaming zip writer.
#[must_use]
pub fn new_buffered_zip_stream_writer() -> BufferedZipStreamWriter {
    BufferedZipStreamWriter::new_stream()
}

/// Creates a new filesystem streaming zip writer.
pub fn new_fs_zip_stream_writer(path: &[u8]) -> Result<FsZipStreamWriter, ZipError> {
    FsZipStreamWriter::new_from_path(path)
}

