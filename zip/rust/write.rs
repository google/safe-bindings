    // Levels zip-rs rejects must be caught by the wrapper first, as
    // InvalidArgument rather than zip-rs's UnsupportedArchive
    // (FailedPrecondition); see `TryFrom<&ZipWriterFileOptions>`.
    #[gtest]
    fn test_out_of_range_compression_levels_are_invalid_argument() {
        let mut writer = BufferedZipWriter::new_from_data(VecU8::default(), false).unwrap();
        let rejected = [
            (CompressionMethod::Deflated, 0),
            (CompressionMethod::Deflated, 10),
            (CompressionMethod::Bzip2, 0),
            (CompressionMethod::Bzip2, 10),
            (CompressionMethod::Xz, -1),
            (CompressionMethod::Xz, 10),
            (CompressionMethod::Zstd, -8),
            (CompressionMethod::Zstd, 23),
            (CompressionMethod::Stored, 0),
            (CompressionMethod::Stored, 6),
            (CompressionMethod::Lzma, 6),
        ];
        for (method, level) in rejected {
            let options =
                ZipWriterFileOptions::new().compression_method(method).compression_level(level);
            let err = writer.start_file(b"file.txt", options).unwrap_err();
            expect_eq!(err.code, ZipErrorCode::InvalidArgument, "{:?} level {}", method, level);
            // add_directory goes through the same options conversion.
            let err = writer.add_directory(b"dir/", options).unwrap_err();
            expect_eq!(err.code, ZipErrorCode::InvalidArgument, "{:?} level {}", method, level);
        }
        // An unset method is validated as Deflated.
        let err = writer
            .start_file(b"file.txt", ZipWriterFileOptions::new().compression_level(0))
            .unwrap_err();
        expect_eq!(err.code, ZipErrorCode::InvalidArgument);
    }

    #[gtest]
    fn test_boundary_compression_levels_round_trip() {
        let accepted = [
            (CompressionMethod::Deflated, 1),
            (CompressionMethod::Deflated, 9),
            (CompressionMethod::Bzip2, 1),
            (CompressionMethod::Bzip2, 9),
            (CompressionMethod::Xz, 0),
            (CompressionMethod::Xz, 9),
            (CompressionMethod::Zstd, -7),
            (CompressionMethod::Zstd, 22),
        ];
        let payload: Vec<u8> = (0..4096).flat_map(|i: u32| i.to_le_bytes()).collect();
        for (method, level) in accepted {
            let mut writer = BufferedZipWriter::new_from_data(VecU8::default(), false).unwrap();
            let options =
                ZipWriterFileOptions::new().compression_method(method).compression_level(level);
            writer.start_file(b"file.bin", options).unwrap();
            writer.write_data(VecU8::from(payload.clone())).unwrap();
            writer.add_directory(b"dir/", options).unwrap();
            let zip_bytes = writer.finish().unwrap();

            let mut archive = BufferedZipArchive::new_from_data(zip_bytes).unwrap();
            expect_eq!(archive.get_length(), 2);
            let mut file = archive.get_file_by_index(0).unwrap();
            expect_eq!(file.get_compression_method(), method, "{:?} level {}", method, level);
            expect_eq!(
                file.get_file_data().unwrap().as_slice(),
                payload.as_slice(),
                "{:?} level {}",
                method,
                level
            );
        }
    }

