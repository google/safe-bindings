// Expose some of the options for writing files to the zip archive.

/// Mirror some of zip::CompressionMethod for Crubit, based on build features.
#[repr(C)]
#[derive(Default, Debug, Clone, Copy, PartialEq, Eq)]
pub enum CompressionMethod {
    #[default]
    Deflated,
    Stored,
    Bzip2,
    Zstd,
    Lzma,
    Xz,
    Unsupported,
}

impl TryFrom<i32> for CompressionMethod {
    type Error = String;

    fn try_from(value: i32) -> Result<Self, Self::Error> {
        match value {
            0 => Ok(CompressionMethod::Stored),
            1 => Ok(CompressionMethod::Deflated),
            2 => Ok(CompressionMethod::Bzip2),
            3 => Ok(CompressionMethod::Zstd),
            4 => Ok(CompressionMethod::Lzma),
            5 => Ok(CompressionMethod::Xz),
            _ => Err(format!("Invalid discriminant for CompressionMethod value: {}", value)),
        }
    }
}

impl CompressionMethod {
    pub fn from_i32(value: i32) -> CompressionMethod {
        match CompressionMethod::try_from(value) {
            Ok(method) => method,
            Err(_) => CompressionMethod::Unsupported,
        }
    }

    /// Maps a method read from an archive onto the mirror, `Unsupported` for
    /// anything the mirror does not name.
    ///
    /// This function won't be generated by Crubit and is only called from
    /// rust. (b/259749095)
    pub(crate) fn from_zip_crate(method: ZipCrateCompressionMethod) -> CompressionMethod {
        match method {
            ZipCrateCompressionMethod::Stored => CompressionMethod::Stored,
            ZipCrateCompressionMethod::Deflated => CompressionMethod::Deflated,
            ZipCrateCompressionMethod::Bzip2 => CompressionMethod::Bzip2,
            ZipCrateCompressionMethod::Zstd => CompressionMethod::Zstd,
            ZipCrateCompressionMethod::Lzma => CompressionMethod::Lzma,
            ZipCrateCompressionMethod::Xz => CompressionMethod::Xz,
            _ => CompressionMethod::Unsupported,
        }
    }

    fn try_into_zip(self) -> Result<ZipCrateCompressionMethod, String> {
        match self {
            CompressionMethod::Deflated => Ok(ZipCrateCompressionMethod::Deflated),
            CompressionMethod::Stored => Ok(ZipCrateCompressionMethod::Stored),
            CompressionMethod::Bzip2 => Ok(ZipCrateCompressionMethod::Bzip2),
            CompressionMethod::Zstd => Ok(ZipCrateCompressionMethod::Zstd),
            CompressionMethod::Lzma => Ok(ZipCrateCompressionMethod::Lzma),
            CompressionMethod::Xz => Ok(ZipCrateCompressionMethod::Xz),
            CompressionMethod::Unsupported => Err("Unsupported compression method".to_string()),
        }
    }
}

#[derive(Default, Debug, Clone, Copy)]
pub struct ZipWriterFileOptions {
    compression_method: Option<CompressionMethod>,
    compression_level: Option<i64>,
    permissions: Option<u32>,
    large_file: Option<bool>,
}

impl TryFrom<&ZipWriterFileOptions> for FileOptions<'static, 'static, ()> {
    type Error = String;

    fn try_from(val: &ZipWriterFileOptions) -> Result<Self, Self::Error> {
        let mut options = FileOptions::<()>::default();
        if let Some(method) = val.compression_method {
            options = options.compression_method(method.try_into_zip()?);
        }
        // Mirrors the ranges zip-rs enforces in `prepare_next_writer`
        // (third_party/rust/zip/v9/src/write.rs); a level outside them is
        // reported by zip-rs as `UnsupportedArchive` (FailedPrecondition), so
        // it is validated here first to return InvalidArgument instead.
        //
        // `None` selects the method's default level.
        //
        // Range of values depends on compression method:
        // * `Deflated` (also the default method): 1 - 9. zip-rs additionally accepts 10 - 264 when
        //   built with Zopfli, which this wrapper does not expose so that archives are produced the
        //   same way regardless of how the crate was built. Default is 6.
        // * `Bzip2`: 1 - 9. Default is 6.
        // * `Zstd`: -7 - 22, with zero being mapped to default level. Default is 3.
        // * `Xz`: 0 - 9. Default is 6.
        // * `Stored` and others: no level is allowed (only `None`).
        if let Some(level) = val.compression_level {
            let method = val.compression_method.unwrap_or_default();
            let in_range = match method {
                CompressionMethod::Deflated | CompressionMethod::Bzip2 => (1..=9).contains(&level),
                CompressionMethod::Xz => (0..=9).contains(&level),
                CompressionMethod::Zstd => (-7..=22).contains(&level),
                _ => false,
            };
            if !in_range {
                return Err(format!(
                    "Compression level {} is out of range for method {:?}",
                    level, method
                ));
            }
            options = options.compression_level(Some(level));
        }
        if let Some(permissions) = val.permissions {
            options = options.unix_permissions(permissions);
        }
        if let Some(large_file) = val.large_file {
            options = options.large_file(large_file);
        }
        Ok(options)
    }
}

impl ZipWriterFileOptions {
    /// Creates a new set of options for writing files to the zip archive.
    pub fn new() -> Self {
        Self::default()
    }

    /// Sets the compression method for the new file.
    pub fn compression_method(mut self, method: CompressionMethod) -> Self {
        self.compression_method = Some(method);
        self
    }

    /// Sets the compression level for the new file.
    ///
    /// The level is validated against `compression_method` (`Deflated` if
    /// unset) when the entry is started: `Deflated` and `Bzip2` accept 1 - 9,
    /// `Xz` 0 - 9, `Zstd` -7 - 22, and `Stored` no level at all. Anything
    /// else makes `start_file` / `add_directory` fail with InvalidArgument.
    pub fn compression_level(mut self, level: i64) -> Self {
        self.compression_level = Some(level);
        self
    }

    /// Sets the Unix permissions for the new file.
    pub fn unix_permissions(mut self, permissions: u32) -> Self {
        self.permissions = Some(permissions);
        self
    }

    /// Sets whether to use large file support for the new file.
    pub fn large_file(mut self, large_file: bool) -> Self {
        self.large_file = Some(large_file);
        self
    }
}

/// A zip writer that writes to an in-memory buffer.
#[derive(Default)]
pub struct BufferedZipWriter {
    writer: Option<Box<WrappedZipWriter<Cursor<Vec<u8>>>>>,
}

impl Debug for BufferedZipWriter {
    fn fmt(&self, f: &mut Formatter) -> std::fmt::Result {
        f.debug_struct("BufferedZipWriter")
            .field("writer", &if self.writer.is_some() { "Some(WrappedZipWriter)" } else { "None" })
            .finish()
    }
}

impl BufferedZipWriter {
    /// Creates a new `BufferedZipWriter`.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Creates a new `BufferedZipWriter` from a byte vector.
    pub fn new_from_data(data: VecU8, append: bool) -> Result<BufferedZipWriter, ZipError> {
        let mut writer = Self::default();
        writer.open(data, append)?;
        Ok(writer)
    }

    /// Opens a zip archive from a byte vector.
    fn open(&mut self, data: VecU8, append: bool) -> Result<(), ZipError> {
        if self.writer.is_some() {
            return Err(ZipError::failed_precondition("Zip writer is already open"));
        }
        let cursor = Cursor::new(data.into_vec());
        let writer = if append {
            WrappedZipWriter::new_append(cursor).map_err(|e| {
                ZipError::from_zip_error(e).with_context("Failed to open zip buffer")
            })?
        } else {
            WrappedZipWriter::new(cursor)
        };
        self.writer = Some(Box::new(writer));
        Ok(())
    }

    /// Returns whether the zip writer is none (due to being
    /// default-constructed or moved-from).
    #[must_use]
    pub fn is_none(&self) -> bool {
        self.writer.is_none()
    }

    /// Finishes writing the zip archive and returns the buffered data.
    pub fn finish(&mut self) -> Result<VecU8, ZipError> {
        finish_impl(&mut self.writer).map(|cursor| cursor.into_inner().into())
    }

    /// Creates a new file in the zip archive and start writing to it.
    pub fn start_file(
        &mut self,
        name: &[u8],
        options: ZipWriterFileOptions,
    ) -> Result<(), ZipError> {
        start_file_impl(&mut self.writer, name, options)
    }

    /// Adds a directory to the zip archive.
    pub fn add_directory(
        &mut self,
        name: &[u8],
        options: ZipWriterFileOptions,
    ) -> Result<(), ZipError> {
        add_directory_impl(&mut self.writer, name, options)
    }

    /// Writes data to the current file in the zip archive.
    pub fn write_data(&mut self, data: VecU8) -> Result<(), ZipError> {
        write_data_impl(&mut self.writer, data)
    }

    // Crubit does not support generic parameters, so we implement `io::copy`
    // helpers for a set of types instead of a generic method.

    /// Writes file content from a `BufferedZipFile` to the current file in the zip archive.
    pub fn write_buffered_zip_file_content(
        &mut self,
        file: &mut BufferedZipFile,
    ) -> Result<(), ZipError> {
        do_copy_impl(&mut self.writer, file)
    }

    /// Writes file content from a `FsZipFile` to the current file in the zip archive.
    pub fn write_fs_zip_file_content(&mut self, file: &mut FsZipFile) -> Result<(), ZipError> {
        do_copy_impl(&mut self.writer, file)
    }

    /// Writes file content from a path to the current file in the zip archive.
    pub fn write_file_content(&mut self, path: &[u8]) -> Result<(), ZipError> {
        write_file_content_impl(&mut self.writer, path)
    }

    /// Sets the archive comment written by `finish`. `comment` must be at most
    /// `u16::MAX` (65535) bytes; a longer comment returns InvalidArgument and
    /// leaves the previously set comment untouched.
    pub fn set_comment(&mut self, comment: &[u8]) -> Result<(), ZipError> {
        set_comment_impl(&mut self.writer, comment)
    }

    /// Flushes the underlying sink; does not finalize the archive.
    pub fn flush(&mut self) -> Result<(), ZipError> {
        flush_impl(&mut self.writer)
    }

    /// Returns whether seeking is possible (always true for BufferedZipWriter).
    #[must_use]
    pub fn is_seek_possible(&self) -> bool {
        true
    }
}

/// A zip writer that writes to a file on the filesystem.
#[derive(Default)]
pub struct FsZipWriter {
    writer: Option<Box<WrappedZipWriter<File>>>,
}

impl Debug for FsZipWriter {
    fn fmt(&self, f: &mut Formatter) -> std::fmt::Result {
        f.debug_struct("FsZipWriter")
            .field("writer", &if self.writer.is_some() { "Some(WrappedZipWriter)" } else { "None" })
            .finish()
    }
}

impl FsZipWriter {
    /// Creates a new `FsZipWriter`.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Creates a new `FsZipWriter` from a path.
    pub fn new_from_path(path: &[u8], append: bool) -> Result<FsZipWriter, ZipError> {
        let mut writer = Self::default();
        writer.open(path, append)?;
        Ok(writer)
    }

    /// Opens a zip archive from a path.
    fn open(&mut self, path: &[u8], append: bool) -> Result<(), ZipError> {
        if self.writer.is_some() {
            return Err(ZipError::failed_precondition("Zip writer is already open"));
        }
        let path_str = ZipError::validate_non_empty_utf8_path(path, "Failed to open zip archive")?;
        let writer = if append {
            // No `.create(true)`: appending to an archive that does not exist
            // must propagate NotFound rather than leave an empty file behind.
            let file = OpenOptions::new().read(true).write(true).open(path_str).map_err(|e| {
                ZipError::from_io_error(e).with_context("Failed to open zip archive")
            })?;
            WrappedZipWriter::new_append(file).map_err(|e| {
                ZipError::from_zip_error(e).with_context("Failed to open zip archive")
            })?
        } else {
            let file =
                OpenOptions::new().write(true).create(true).truncate(true).open(path_str).map_err(
                    |e| ZipError::from_io_error(e).with_context("Failed to open zip archive"),
                )?;
            WrappedZipWriter::new(file)
        };
        self.writer = Some(Box::new(writer));
        Ok(())
    }

    /// Returns whether the zip writer is none (due to being
    /// default-constructed or moved-from).
    #[must_use]
    pub fn is_none(&self) -> bool {
        self.writer.is_none()
    }

    /// Finishes writing the zip archive to file.
    pub fn finish(&mut self) -> Result<(), ZipError> {
        finish_impl(&mut self.writer).map(|_| ())
    }

    /// Creates a new file in the zip archive and start writing to it.
    pub fn start_file(
        &mut self,
        name: &[u8],
        options: ZipWriterFileOptions,
    ) -> Result<(), ZipError> {
        start_file_impl(&mut self.writer, name, options)
    }

    /// Adds a directory to the zip archive.
    pub fn add_directory(
        &mut self,
        name: &[u8],
        options: ZipWriterFileOptions,
    ) -> Result<(), ZipError> {
        add_directory_impl(&mut self.writer, name, options)
    }

    /// Writes data to the current file in the zip archive.
    pub fn write_data(&mut self, data: VecU8) -> Result<(), ZipError> {
        write_data_impl(&mut self.writer, data)
    }

    // Crubit does not support generic parameters, so we implement `io::copy`
    // helpers for a set of types instead of a generic method.

    /// Writes file content from a `BufferedZipFile` to the current file in the zip archive.
    pub fn write_buffered_zip_file_content(
        &mut self,
        file: &mut BufferedZipFile,
    ) -> Result<(), ZipError> {
        do_copy_impl(&mut self.writer, file)
    }

    /// Writes file content from a `FsZipFile` to the current file in the zip archive.
    pub fn write_fs_zip_file_content(&mut self, file: &mut FsZipFile) -> Result<(), ZipError> {
        do_copy_impl(&mut self.writer, file)
    }

    /// Writes file content from a path to the current file in the zip archive.
    pub fn write_file_content(&mut self, path: &[u8]) -> Result<(), ZipError> {
        write_file_content_impl(&mut self.writer, path)
    }

    /// Sets the archive comment written by `finish`. `comment` must be at most
    /// `u16::MAX` (65535) bytes; a longer comment returns InvalidArgument and
    /// leaves the previously set comment untouched.
    pub fn set_comment(&mut self, comment: &[u8]) -> Result<(), ZipError> {
        set_comment_impl(&mut self.writer, comment)
    }

    /// Flushes the underlying sink; does not finalize the archive.
    pub fn flush(&mut self) -> Result<(), ZipError> {
        flush_impl(&mut self.writer)
    }

    /// Returns whether seeking is possible (always true for FsZipWriter).
    #[must_use]
    pub fn is_seek_possible(&self) -> bool {
        true
    }
}

fn start_file_impl<W: Write + Seek>(
    writer: &mut Option<Box<WrappedZipWriter<W>>>,
    name: &[u8],
    options: ZipWriterFileOptions,
) -> Result<(), ZipError> {
    let writer =
        writer.as_deref_mut().ok_or_else(|| ZipError::failed_precondition("writer is not open"))?;
    let name_str = std::str::from_utf8(name)
        .map_err(|e| ZipError::invalid_argument(format!("Entry name is not valid UTF-8: {}", e)))?;
    let file_options = FileOptions::try_from(&options).map_err(ZipError::invalid_argument)?;
    writer.start_file(name_str, file_options).map_err(ZipError::from_zip_error)
}

fn add_directory_impl<W: Write + Seek>(
    writer: &mut Option<Box<WrappedZipWriter<W>>>,
    name: &[u8],
    options: ZipWriterFileOptions,
) -> Result<(), ZipError> {
    let writer =
        writer.as_deref_mut().ok_or_else(|| ZipError::failed_precondition("writer is not open"))?;
    let name_str = std::str::from_utf8(name)
        .map_err(|e| ZipError::invalid_argument(format!("Entry name is not valid UTF-8: {}", e)))?;
    let file_options = FileOptions::try_from(&options).map_err(ZipError::invalid_argument)?;
    writer.add_directory(name_str, file_options).map_err(ZipError::from_zip_error)
}

// zip-rs only reports "No file has been started" from `ZipWriter::write`,
// which `write_all(&[])` and `io::copy` from an empty source never call, and
// `io::copy` from a non-empty source reads (and so consumes) up to 8 KiB of it
// before the first failing write. Check up front instead so that all Write*
// methods fail the same way, without consuming the source, when no entry is
// open (including right after `add_directory`).
fn check_writing_file<W: Write + Seek>(writer: &WrappedZipWriter<W>) -> Result<(), ZipError> {
    if writer.is_writing_file() {
        Ok(())
    } else {
        Err(ZipError::internal("No file has been started"))
    }
}

fn write_data_impl<W: Write + Seek>(
    writer: &mut Option<Box<WrappedZipWriter<W>>>,
    data: VecU8,
) -> Result<(), ZipError> {
    let writer =
        writer.as_deref_mut().ok_or_else(|| ZipError::failed_precondition("writer is not open"))?;
    check_writing_file(writer)?;
    writer.write_all(data.as_slice()).map_err(ZipError::from_io_error)
}

fn do_copy_impl<W: Write + Seek, R: Read>(
    writer: &mut Option<Box<WrappedZipWriter<W>>>,
    reader: &mut R,
) -> Result<(), ZipError> {
    let writer =
        writer.as_deref_mut().ok_or_else(|| ZipError::failed_precondition("writer is not open"))?;
    check_writing_file(writer)?;
    copy(reader, writer).map(|_| ()).map_err(ZipError::from_io_error)
}

fn write_file_content_impl<W: Write + Seek>(
    writer: &mut Option<Box<WrappedZipWriter<W>>>,
    path: &[u8],
) -> Result<(), ZipError> {
    let writer =
        writer.as_deref_mut().ok_or_else(|| ZipError::failed_precondition("writer is not open"))?;
    let path_str = ZipError::validate_non_empty_utf8_path(path, "Failed to read source file")?;
    let mut file = File::open(path_str)
        .map_err(|e| ZipError::from_io_error(e).with_context("Failed to read source file"))?;
    // After validating and opening `path`, so that path and open errors keep
    // precedence as documented in write.h.
    check_writing_file(writer)?;
    copy(&mut file, writer).map(|_| ()).map_err(ZipError::from_io_error)
}

fn set_comment_impl<W: Write + Seek>(
    writer: &mut Option<Box<WrappedZipWriter<W>>>,
    comment: &[u8],
) -> Result<(), ZipError> {
    let writer =
        writer.as_deref_mut().ok_or_else(|| ZipError::failed_precondition("writer is not open"))?;
    // Checked up front: zip-rs's `set_raw_comment` stores the first
    // `u16::MAX` bytes and only then returns an error, which would leave a
    // silently truncated comment in the finished archive.
    if comment.len() > u16::MAX as usize {
        return Err(ZipError::invalid_argument(format!(
            "archive comment is {} bytes; at most {} allowed",
            comment.len(),
            u16::MAX
        )));
    }
    writer.set_raw_comment(Box::from(comment)).map_err(ZipError::from_zip_error)
}

fn flush_impl<W: Write + Seek>(
    writer: &mut Option<Box<WrappedZipWriter<W>>>,
) -> Result<(), ZipError> {
    let writer =
        writer.as_deref_mut().ok_or_else(|| ZipError::failed_precondition("writer is not open"))?;
    writer.flush().map_err(ZipError::from_io_error)
}

/// Writes the central directory and consumes the inner writer, returning the
/// underlying sink.
fn finish_impl<W: Write + Seek>(
    writer: &mut Option<Box<WrappedZipWriter<W>>>,
) -> Result<W, ZipError> {
    match writer.take() {
        Some(writer) => writer.finish().map_err(ZipError::from_zip_error),
        None => Err(ZipError::failed_precondition("writer is not open")),
    }
}

/// `set_comment` for the streaming writers. Archive comments are not
/// supported by them: zip 9.x finalizes a commented archive by seeking back
/// over the comment, which a non-seekable writer cannot do
/// (`zip::write::StreamWriter` only permits no-op seeks). The open check comes
/// first so that a moved-from or finished stream writer reports "writer is not
/// open" like every other method; an open one reports "not supported". Both
/// are FailedPrecondition errors.
fn set_stream_comment_impl<W: Write + Seek>(
    writer: &Option<Box<WrappedZipWriter<W>>>,
) -> Result<(), ZipError> {
    if writer.is_none() {
        return Err(ZipError::failed_precondition("writer is not open"));
    }
    Err(ZipError::failed_precondition(
        "archive comments are not supported by streaming zip writers",
    ))
}

type InnerBufferedStreamWriter = WrappedZipWriter<StreamWriter<Cursor<Vec<u8>>>>;
// The file is wrapped in a `BufWriter` so that the many small writes zip-rs
// issues per entry (header fields, data descriptor) do not each become a
// `write(2)` syscall; `FsZipStreamWriter::finish` flushes it.
type InnerFsStreamWriter = WrappedZipWriter<StreamWriter<BufWriter<File>>>;

/// A zip writer that streams to an in-memory buffer without seeking.
