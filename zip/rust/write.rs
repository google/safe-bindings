    #[gtest]
    fn test_writer_error_propagation() {
        let base_dir = std::env::var_os("TEST_TMPDIR")
            .map(std::path::PathBuf::from)
            .unwrap_or_else(std::env::temp_dir)
            .join("writer_error_propagation_test");
        std::fs::create_dir_all(&base_dir).unwrap();

        // Invalid UTF-8 path in FsZipWriter::new_from_path does not create a file.
        let mut invalid_path = base_dir.to_str().unwrap().as_bytes().to_vec();
        invalid_path.extend_from_slice(b"/bad_\xff_seekable.zip");
        expect_eq!(
            FsZipWriter::new_from_path(&invalid_path, false).unwrap_err().code,
            ZipErrorCode::InvalidArgument
        );
        expect_eq!(std::fs::read_dir(&base_dir).unwrap().count(), 0);

        // Missing parent directory propagates NotFound for both FsZipWriter and FsZipStreamWriter.
        let missing_parent_zip = base_dir.join("missing_parent/out.zip");
        expect_eq!(
            FsZipWriter::new_from_path(missing_parent_zip.to_str().unwrap().as_bytes(), false)
                .unwrap_err()
                .code,
            ZipErrorCode::NotFound
        );
        expect_eq!(
            FsZipStreamWriter::new_from_path(missing_parent_zip.to_str().unwrap().as_bytes())
                .unwrap_err()
                .code,
            ZipErrorCode::NotFound
        );

        // Unsupported compression method variant returns InvalidArgument instead of panicking.
        let mut writer = BufferedZipWriter::new_from_data(VecU8::default(), false).unwrap();
        let bad_opts =
            ZipWriterFileOptions::new().compression_method(CompressionMethod::Unsupported);
        expect_eq!(
            writer.start_file(b"bad_method.txt", bad_opts).unwrap_err().code,
            ZipErrorCode::InvalidArgument
        );

        // Invalid UTF-8, duplicate, and overlong entry names return InvalidArgument.
        let opts = ZipWriterFileOptions::new();
        expect_eq!(
            writer.start_file(b"bad_\xff.txt", opts).unwrap_err().code,
            ZipErrorCode::InvalidArgument
        );
        expect_eq!(
            writer.add_directory(b"bad_\xff/", opts).unwrap_err().code,
            ZipErrorCode::InvalidArgument
        );
        let overlong_name = vec![b'a'; 65536];
        expect_eq!(
            writer.start_file(&overlong_name, opts).unwrap_err().code,
            ZipErrorCode::InvalidArgument
        );
        expect_eq!(
            writer.add_directory(&overlong_name, opts).unwrap_err().code,
            ZipErrorCode::InvalidArgument
        );
        writer.start_file(b"dup.txt", opts).unwrap();
        expect_eq!(
            writer.start_file(b"dup.txt", opts).unwrap_err().code,
            ZipErrorCode::InvalidArgument
        );

        // write_file_content propagates NotFound on missing source file and InvalidArgument on bad
        // path.
        expect_eq!(
            writer
                .write_file_content(
                    base_dir.join("does_not_exist.bin").to_str().unwrap().as_bytes()
                )
                .unwrap_err()
                .code,
            ZipErrorCode::NotFound
        );
        expect_eq!(writer.write_file_content(b"").unwrap_err().code, ZipErrorCode::InvalidArgument);
        expect_eq!(
            writer.write_file_content(b"\xff").unwrap_err().code,
            ZipErrorCode::InvalidArgument
        );
    }

