    // Builds an archive with a 0-byte entry (index 0) and a non-empty one
    // (index 1) for the "no open entry" tests below.
    fn build_empty_and_full_entry_archive() -> VecU8 {
        let mut writer = BufferedZipWriter::new_from_data(VecU8::default(), false).unwrap();
        let options = ZipWriterFileOptions::new();
        writer.start_file(b"empty.txt", options).unwrap();
        writer.start_file(b"full.txt", options).unwrap();
        writer.write_data(VecU8::from(b"full content".to_vec())).unwrap();
        writer.finish().unwrap()
    }

    // Shared by the seekable and streaming writer tests below: every write
    // method is Internal while no entry is open, even for empty inputs and
    // 0-byte sources (for which zip-rs itself would never raise an error,
    // because nothing is ever written to it), and a non-empty source is not
    // consumed by the failed call.
    macro_rules! expect_writes_without_open_entry_are_internal {
        ($writer:expr, $source:expr, $empty_file:expr, $missing_file:expr) => {{
            let options = ZipWriterFileOptions::new();
            // Before any start_file.
            expect_eq!(
                $writer.write_data(VecU8::default()).unwrap_err().code,
                ZipErrorCode::Internal
            );
            expect_eq!(
                $writer.write_data(VecU8::from(b"data".to_vec())).unwrap_err().code,
                ZipErrorCode::Internal
            );
            {
                let mut empty_entry = $source.get_file_by_index(0).unwrap();
                expect_eq!(
                    $writer.write_buffered_zip_file_content(&mut empty_entry).unwrap_err().code,
                    ZipErrorCode::Internal
                );
            }
            {
                let mut full_entry = $source.get_file_by_index(1).unwrap();
                expect_eq!(
                    $writer.write_buffered_zip_file_content(&mut full_entry).unwrap_err().code,
                    ZipErrorCode::Internal
                );
                // Not consumed by the failed call.
                expect_eq!(full_entry.get_file_data().unwrap().as_slice(), b"full content");
            }
            // write_file_content: an existing 0-byte file reaches the check,
            // whereas path and open errors keep precedence over it.
            expect_eq!(
                $writer.write_file_content($empty_file).unwrap_err().code,
                ZipErrorCode::Internal
            );
            expect_eq!(
                $writer.write_file_content($missing_file).unwrap_err().code,
                ZipErrorCode::NotFound
            );
            expect_eq!(
                $writer.write_file_content(b"").unwrap_err().code,
                ZipErrorCode::InvalidArgument
            );
            // Right after add_directory.
            $writer.add_directory(b"d/", options).unwrap();
            expect_eq!(
                $writer.write_data(VecU8::default()).unwrap_err().code,
                ZipErrorCode::Internal
            );
            // With an entry open the same calls succeed.
            $writer.start_file(b"f.txt", options).unwrap();
            $writer.write_data(VecU8::default()).unwrap();
            $writer.write_file_content($empty_file).unwrap();
            {
                let mut full_entry = $source.get_file_by_index(1).unwrap();
                $writer.write_buffered_zip_file_content(&mut full_entry).unwrap();
            }
        }};
    }

    #[gtest]
    fn test_writes_without_an_open_entry_are_internal() {
        let base_dir = std::env::var_os("TEST_TMPDIR")
            .map(std::path::PathBuf::from)
            .unwrap_or_else(std::env::temp_dir)
            .join("writes_without_open_entry_test");
        std::fs::create_dir_all(&base_dir).unwrap();
        let empty_file = base_dir.join("empty.bin");
        std::fs::write(&empty_file, b"").unwrap();
        let empty_file = empty_file.to_str().unwrap().as_bytes();
        let missing_file = base_dir.join("missing.bin");
        let missing_file = missing_file.to_str().unwrap().as_bytes();
        let mut source =
            BufferedZipArchive::new_from_data(build_empty_and_full_entry_archive()).unwrap();

        let mut seekable = BufferedZipWriter::new_from_data(VecU8::default(), false).unwrap();
        expect_writes_without_open_entry_are_internal!(seekable, source, empty_file, missing_file);
        let seekable_bytes = seekable.finish().unwrap();
        expect_eq!(BufferedZipArchive::new_from_data(seekable_bytes).unwrap().get_length(), 2);

        let mut stream = BufferedZipStreamWriter::new_stream();
        expect_writes_without_open_entry_are_internal!(stream, source, empty_file, missing_file);
        let stream_bytes = stream.finish().unwrap();
        expect_eq!(BufferedZipArchive::new_from_data(stream_bytes).unwrap().get_length(), 2);
    }
