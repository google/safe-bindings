//! A zip entry's central directory record, readable without any I/O.
//!
//! Crubit does not support generic type parameters, so the archive types that
//! hand these out are written out one by one; this type itself owns its data
//! and so is shared by all of them.

use crate::write::CompressionMethod;
use crate::VecU8;
use zip::read::ZipArchiveMetadata;
use zip::CompressionMethod as ZipCrateCompressionMethod;

/// What a zip archive's central directory records about one entry.
///
/// Every field here is read when the archive is opened, so obtaining this
/// costs no I/O. Note the contrast with `*ZipFile`, which additionally seeks
/// to the entry's local file header in order to find where its data begins:
/// listing an archive through `get_file_by_index` therefore costs one read per
/// entry, which is ruinous when the archive is behind a network. Prefer this
/// whenever the entry's contents are not wanted.
///
/// Correspondingly, this deliberately has no `get_data_start()`: that offset
/// is the one piece of per-entry information that is not in the central
/// directory. Open the entry if you need it.
#[derive(Debug)]
pub struct ZipEntryMetadata {
    name: Vec<u8>,
    comment: Vec<u8>,
    uncompressed_size: u64,
    compressed_size: u64,
    header_start: u64,
    crc32: u32,
    unix_mode: u32,
    last_modified_date: u16,
    last_modified_time: u16,
    compression_method: CompressionMethod,
    is_dir: bool,
    is_file: bool,
    is_encrypted: bool,
}

impl Default for ZipEntryMetadata {
    /// The default value exists only so that Crubit can generate a movable
    /// type; it describes no entry.
    fn default() -> Self {
        Self {
            name: Vec::new(),
            comment: Vec::new(),
            uncompressed_size: 0,
            compressed_size: 0,
            header_start: 0,
            crc32: 0,
            unix_mode: 0,
            last_modified_date: 0,
            last_modified_time: 0,
            compression_method: CompressionMethod::Unsupported,
            is_dir: false,
            is_file: false,
            is_encrypted: false,
        }
    }
}

impl ZipEntryMetadata {
    /// Copies out what `metadata` records about the entry at `index`, or
    /// `None` if there is no such entry.
    ///
    /// This function won't be generated by Crubit and is only called from
    /// rust. (b/259749095)
    pub(crate) fn from_central_directory(
        metadata: &ZipArchiveMetadata,
        index: usize,
    ) -> Option<Self> {
        let entry = metadata.entry(index).ok()?;
        let last_modified = entry.last_modified();
        Some(Self {
            // Decoded the same way as `*ZipFile::get_file_name`, so that listing
            // and opening an entry agree on its name (UTF-8, else CP437).
            name: match entry.name() {
                Ok(name) => name.as_bytes().to_vec(),
                Err(_) => entry.name_raw().to_vec(),
            },
            comment: entry.comment().as_bytes().to_vec(),
            uncompressed_size: entry.size(),
            compressed_size: entry.compressed_size(),
            header_start: entry.header_start(),
            crc32: entry.crc32(),
            unix_mode: entry.unix_mode().unwrap_or(0),
            last_modified_date: last_modified.map(|dt| dt.datepart()).unwrap_or(0),
            last_modified_time: last_modified.map(|dt| dt.timepart()).unwrap_or(0),
            compression_method: match entry.compression() {
                ZipCrateCompressionMethod::STORE => CompressionMethod::Stored,
                ZipCrateCompressionMethod::DEFLATE => CompressionMethod::Deflated,
                ZipCrateCompressionMethod::BZIP2 => CompressionMethod::Bzip2,
                ZipCrateCompressionMethod::ZSTD => CompressionMethod::Zstd,
                ZipCrateCompressionMethod::LZMA => CompressionMethod::Lzma,
                ZipCrateCompressionMethod::XZ => CompressionMethod::Xz,
                _ => CompressionMethod::Unsupported,
            },
            is_dir: entry.is_dir(),
            is_file: entry.is_file(),
            is_encrypted: entry.encrypted(),
        })
    }

    /// Returns the name of the entry.
    pub fn get_file_name(&self) -> VecU8 {
        VecU8::copy_from_slice(&self.name)
    }

    /// Returns whether the entry is a file, that is, neither a directory nor a
    /// symbolic link.
    pub fn is_file(&self) -> bool {
        self.is_file
    }

    /// Returns whether the entry is a directory.
    pub fn is_dir(&self) -> bool {
        self.is_dir
    }

    /// Returns whether the entry's data is encrypted. This library does not
    /// decrypt, so such an entry can be listed but not read.
    pub fn is_encrypted(&self) -> bool {
        self.is_encrypted
    }

    /// Returns the compression method of the entry.
    pub fn get_compression_method(&self) -> CompressionMethod {
        self.compression_method
    }

    /// Returns the comment on the entry.
    pub fn get_comment(&self) -> VecU8 {
        VecU8::copy_from_slice(&self.comment)
    }

    /// Returns the uncompressed size of the entry.
    pub fn get_uncompressed_size(&self) -> u64 {
        self.uncompressed_size
    }

    /// Returns the compressed size of the entry.
    pub fn get_compressed_size(&self) -> u64 {
        self.compressed_size
    }

    /// Returns the CRC32 of the entry.
    pub fn get_crc32(&self) -> u32 {
        self.crc32
    }

    /// Returns the last modified date of the entry in DOS format, or 0 if it
    /// does not record one.
    pub fn get_last_modified_date(&self) -> u16 {
        self.last_modified_date
    }

    /// Returns the last modified time of the entry in DOS format, or 0 if it
    /// does not record one.
    pub fn get_last_modified_time(&self) -> u16 {
        self.last_modified_time
    }

    /// Returns the Unix mode of the entry, or 0 if it does not record one.
    pub fn get_unix_mode(&self) -> u32 {
        self.unix_mode
    }

    /// Returns the offset of the entry's local file header in the archive.
    pub fn get_header_start(&self) -> u64 {
        self.header_start
    }
}
