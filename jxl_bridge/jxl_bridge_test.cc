// Decodes a single-frame grayscale image to host-endian 16-bit samples.
absl::StatusOr<std::vector<uint16_t>> DecodeGray16(
    absl::Span<const uint8_t> data) {
  absl::StatusOr<DecodedImage> image =
      DecodeJxl(data, DataType::U16, ChannelLayout::Grayscale);
  if (!image.ok()) return image.status();
  std::vector<uint16_t> samples(image->pixels.size() / sizeof(uint16_t));
  std::memcpy(samples.data(), image->pixels.data(),
              samples.size() * sizeof(uint16_t));
  return samples;
}

// Byte 53 of kGray16Image holds a header bit that libjxl's decoder ignores:
// djxl decodes the image to the same pixels whether the bit is set or not. The
// bit is believed to be modular_16bit_buffer_sufficient, which claims that
// 16-bit buffers can hold the image's samples. The claim is false for this
// image, so the modified file is not a conforming stream, and a decoder may
// reject it. What it must not do is return different pixels without an error.
TEST(JxlBridgeTest, FlippedHeaderBitDoesNotSilentlyChangePixels) {
  std::vector<uint8_t> flipped(std::begin(kGray16Image),
                               std::end(kGray16Image));
  flipped[53] ^= 0x10;

  const absl::StatusOr<std::vector<uint16_t>> expected =
      DecodeGray16(kGray16Image);
  ASSERT_TRUE(expected.ok()) << expected.status();
  ASSERT_EQ(expected->size(), 32 * 32);

  const absl::StatusOr<std::vector<uint16_t>> actual = DecodeGray16(flipped);
  if (!actual.ok()) return;  // Rejecting the image is fine.
  ASSERT_EQ(actual->size(), expected->size());

  size_t differing = 0;
  size_t first = 0;
  for (size_t i = 0; i < expected->size(); ++i) {
    if ((*actual)[i] == (*expected)[i]) continue;
    if (differing++ == 0) first = i;
  }
  EXPECT_EQ(differing, 0) << "decoding succeeded but " << differing << " of "
                          << expected->size()
                          << " samples changed; the first is sample " << first
                          << ": " << (*expected)[first] << " became "
                          << (*actual)[first];
}

